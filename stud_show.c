void show_student(S *ptr)
{
    if(ptr == 0)
    {
        printf("No records found\n");
        return;
    }

    printf("----------------------------------------------------\n");
    printf("%-10s %-20s %-10s\n", "Roll No.", "Name", "Marks");
    printf("----------------------------------------------------\n");

    while(ptr)
    {
        printf("%-10d %-20s %-30.6lf\n", ptr->rollno, ptr->name, ptr->marks);
        ptr = ptr->next;
    }

    printf("----------------------------------------------------\n");
}
